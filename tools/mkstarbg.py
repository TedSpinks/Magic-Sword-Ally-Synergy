keys=[(0,(193,206,209)),(0.15,(139,144,166)),(0.32,(104,85,107)),(0.5,(51,52,120)),(0.7,(21,13,74)),(1.0,(11,13,64))]
def ramp(t):
    for (a,ca),(b,cb) in zip(keys,keys[1:]):
        if a<=t<=b:
            f=(t-a)/(b-a); return tuple(int(ca[i]+(cb[i]-ca[i])*f) for i in range(3))
