import random
random.seed(1990)
def bgr(r,g,b): return ((b>>3)<<10)|((g>>3)<<5)|(r>>3)
def hexc(h): return bgr(int(h[1:3],16),int(h[3:5],16),int(h[5:7],16))
# tiles
tiles=[bytes(32)]
pos={}
for c in range(1,8):
    for v in range(4):
        x=random.randint(1,6); y=random.randint(1,6)
        t=bytearray(32)
        for p in range(4):
            if (c>>p)&1:
                t[(0 if p<2 else 16)+2*y+(p&1)] |= 1<<(7-x)
        tiles.append(bytes(t))
gfx=b''.join(tiles)
# map
text_rows=set(range(5,25,2))
cells=[]
for row in range(28):
    for col in range(32):
        if row in (1,2) and 2<=col<=30: continue
        if row in text_rows and 2<=col<=31: continue
        if row==26 and 3<=col<=29: continue
        if random.random()<0.42:
            r=random.random()
            c = random.choice([4,5,5,6,6,6]) if r<0.70 else (7 if r<0.80 else random.choice([1,2,3]))
            v=random.randint(0,3)
            cells.append((row*32+col, (1+(c-1)*4+v)|0x0C00))
out=["; generated by scripts/mkstarbg.py: BG2 star field (tile 0 blank; colours 1-3 twinkle, 4-7 static)\nBgStarGfx:"]
for i in range(0,len(gfx),16): out.append("    db "+",".join("$%02X"%b for b in gfx[i:i+16]))
out.append("BgStarGfxEnd:")
out.append("BgStarPal: dw $0000,$0000,$0000,$0000,$%04X,$%04X,$%04X,$%04X"%(hexc('#3F4D7E'),hexc('#2C3668'),hexc('#1E2652'),hexc('#96B4D4')))
out.append("BgStarMap:")
for i in range(0,len(cells),4): out.append("    dw "+",".join("$%04X,$%04X"%e for e in cells[i:i+4]))
out.append("    dw $FFFF")
open('asm/starbg.inc','w').write("\n".join(out)+"\n")
print(len(cells),'stars',len(gfx))
